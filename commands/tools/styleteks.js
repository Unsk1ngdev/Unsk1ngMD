const UPSIDE_DOWN_MAP = {
    a: 'ɐ', b: 'q', c: 'ɔ', d: 'p', e: 'ǝ', f: 'ɟ', g: 'ƃ', h: 'ɥ', i: 'ᴉ', j: 'ɾ', k: 'ʞ', l: 'l', m: 'ɯ',
    n: 'u', o: 'o', p: 'd', q: 'b', r: 'ɹ', s: 's', t: 'ʇ', u: 'n', v: 'ʌ', w: 'ʍ', x: 'x', y: 'ʎ', z: 'z',
    A: '∀', B: 'ᗺ', C: 'Ɔ', D: 'ᗡ', E: 'Ǝ', F: 'Ⅎ', G: 'פ', H: 'H', I: 'I', J: 'ſ', K: 'ʞ', L: '˥', M: 'W',
    N: 'N', O: 'O', P: 'Ԁ', Q: 'Ό', R: 'ᴚ', S: 'S', T: '⊥', U: '∩', V: 'Λ', W: 'M', X: 'X', Y: '⅄', Z: 'Z',
    '?': '¿', '!': '¡', '.': '˙', ',': '\'', '(': ')', ')': '(', '[': ']', ']': '[', '{': '}', '}': '{'
};

function transformText(text, map) {
    return text.split('').map(char => map[char] || char).join('');
}

function flipText(text) {
    return text.split('').reverse().map(char => UPSIDE_DOWN_MAP[char] || char).join('');
}

module.exports = {
    name: 'styleteks',
    alias: ['estilotexto', 'fancytext', 'styletext', 'fuentes', 'letras'],
    category: 'herramientas',
    desc: 'Convierte tu texto a más de 10 estilos tipográficos elegantes y llamativos',
    usage: '.styleteks <texto>',

    execute: async ({ sock, m, args, text }) => {
        const jid = m.chat || m.key.remoteJid;
        const input = (args && args.length > 0 ? args.join(' ') : (text || m.quoted?.body || '')).trim();

        if (!input) {
            return await sock.sendMessage(jid, {
                text: [
                    '┏❐ 《 ✨ ESTILIZADOR DE TEXTO 》 ❐',
                    '┃',
                    '┃├◆ 📋 *Uso:* `.styleteks <texto>`',
                    '┃├◆ 📌 *Ejemplo:* `.styleteks Hola Mundo`',
                    '┃',
                    '┃├◆ 🔠 Transforma cualquier texto en fuentes bonitas:',
                    '┃  cursivas, dobles, góticas, invertidas, etc.',
                    '┗❐\n',
                    '_Unknown Codexツ</>_'
                ].join('\n')
            }, { quoted: m });
        }

        const lines = [
            '┏❐ 《 ✨ ESTILOS DE TEXTO GENERADOS 》 ❐',
            '┃',
            `┃├◆ 📥 *Original:* ${input}`,
            '┃'
        ];

        let index = 1;
        for (const [styleName, map] of Object.entries(FONT_MAPS)) {
            const transformed = transformText(input, map);
            lines.push(`┃ ${index++}. *${styleName}:*`);
            lines.push(`┃ ${transformed}`);
            lines.push('┃');
        }

        // Invertido / Upside down
        const upside = flipText(input);
        lines.push(`┃ ${index}. *Invertido (De Cabeza):*`);
        lines.push(`┃ ${upside}`);
        lines.push('┗❐\n');
        lines.push('_Copia tu estilo favorito y úsalo donde quieras._');
        lines.push('_Unknown Codexツ</>_');

        await m.react?.('✨');
        await sock.sendMessage(jid, { text: lines.join('\n') }, { quoted: m });
    }
};

